"""Checks the Main Module's phone-protocol bytes on a computer.

    python "Tools/Phone Link Test/run_test.py"

1. Copies the block between "// BEGIN PHONE WIRE" and "// END PHONE WIRE" out
   of "Main Module/main_module.ino" into phone_wire.inc (not committed).
2. Compiles host_test.cpp with a C++ compiler on this computer: c++, g++ or
   clang++ if installed, otherwise `python -m ziglang c++` (pip install ziglang).
3. Runs it: it checks the block and writes firmware_notifications.txt.
4. Then run the phone app's test, which decodes that file with the app's own
   code:  cd "Phone App/app" && flutter test test/firmware_vectors_test.dart

Commit firmware_notifications.txt whenever it changes.
"""
import os
import shutil
import subprocess
import sys
import tempfile

here = os.path.dirname(os.path.abspath(__file__))
repo = os.path.dirname(os.path.dirname(here))
sketch = os.path.join(repo, 'Main Module', 'main_module.ino')

text = open(sketch, encoding='utf-8').read()
begin, end = '// BEGIN PHONE WIRE', '// END PHONE WIRE'
if text.count(begin) != 1 or text.count(end) != 1:
    sys.exit('main_module.ino must contain exactly one BEGIN/END PHONE WIRE pair')
block = text[text.index(begin):text.index(end) + len(end)]
with open(os.path.join(here, 'phone_wire.inc'), 'w', encoding='utf-8', newline='\n') as f:
    f.write('// Generated by run_test.py from Main Module/main_module.ino. Do not edit.\n' + block + '\n')

compiler = next(([c] for c in ('c++', 'g++', 'clang++') if shutil.which(c)), None)
if compiler is None:
    try:
        import ziglang  # noqa: F401
        compiler = [sys.executable, '-m', 'ziglang', 'c++']
    except ImportError:
        sys.exit('No C++ compiler found. Install one, or: pip install ziglang')

with tempfile.TemporaryDirectory() as tmp:
    exe = os.path.join(tmp, 'host_test.exe' if os.name == 'nt' else 'host_test')
    subprocess.run(compiler + ['-std=c++17', '-O1', '-Wall', '-Wextra', '-Werror', '-I', here,
                               os.path.join(here, 'host_test.cpp'), '-o', exe], check=True)
    result = subprocess.run([exe, os.path.join(here, 'firmware_notifications.txt')])
sys.exit(result.returncode)
