"""Checks the firmware's phone-link code on a computer, without hardware.

    python "Tools/Phone Link Test/run_test.py"

Main Module (Bluetooth bytes the module sends to the phone):
1. Copies the block between "// BEGIN PHONE WIRE" and "// END PHONE WIRE" out
   of "Main Module/main_module.ino" into phone_wire.inc (not committed).
2. Compiles and runs host_test.cpp: it checks the block and writes
   firmware_notifications.txt. Then run the phone app's test, which decodes
   that file with the app's own code:
       cd "Phone App/app" && flutter test test/firmware_vectors_test.dart
   Commit firmware_notifications.txt whenever it changes.

Front Module (phone screens the module must draw):
3. Copies the block between "// BEGIN SCREEN DECODER" and "// END SCREEN
   DECODER" out of "Front Module/front_module.ino" into screen_decoder.inc.
4. Runs `dart run tool/export_screens.dart` in Phone App/navigation (needs
   the Dart or Flutter SDK on PATH) to get the 415 test screens, then compiles
   and runs front_test.cpp, which decodes every screen 4 ways and compares
   it pixel by pixel with what the app drew. Skipped if Dart isn't found.

C++ compiler: c++, g++ or clang++ if installed, otherwise
`python -m ziglang c++` (pip install ziglang).
"""
import os
import shutil
import subprocess
import sys
import tempfile

here = os.path.dirname(os.path.abspath(__file__))
repo = os.path.dirname(os.path.dirname(here))


def extract(sketch, name, out):
    text = open(os.path.join(repo, sketch), encoding='utf-8').read()
    begin, end = '// BEGIN ' + name, '// END ' + name
    if text.count(begin) != 1 or text.count(end) != 1:
        sys.exit(f'{sketch} must contain exactly one BEGIN/END {name} pair')
    block = text[text.index(begin):text.index(end) + len(end)]
    with open(os.path.join(here, out), 'w', encoding='utf-8', newline='\n') as f:
        f.write(f'// Generated by run_test.py from {sketch}. Do not edit.\n' + block + '\n')


compiler = next(([c] for c in ('c++', 'g++', 'clang++') if shutil.which(c)), None)
if compiler is None:
    try:
        import ziglang  # noqa: F401
        compiler = [sys.executable, '-m', 'ziglang', 'c++']
    except ImportError:
        sys.exit('No C++ compiler found. Install one, or: pip install ziglang')


def build(source, exe):
    subprocess.run(compiler + ['-std=c++17', '-O1', '-Wall', '-Wextra', '-Werror', '-I', here,
                               os.path.join(here, source), '-o', exe], check=True)


extract('Main Module/main_module.ino', 'PHONE WIRE', 'phone_wire.inc')
extract('Front Module/front_module.ino', 'SCREEN DECODER', 'screen_decoder.inc')
failed = False
with tempfile.TemporaryDirectory() as tmp:
    ext = '.exe' if os.name == 'nt' else ''
    main_exe = os.path.join(tmp, 'host_test' + ext)
    build('host_test.cpp', main_exe)
    failed |= subprocess.run([main_exe, os.path.join(here, 'firmware_notifications.txt')]).returncode != 0

    dart = shutil.which('dart')
    if dart is None:
        print('Front decoder test skipped: put the Dart or Flutter SDK on PATH to run it.')
    else:
        screens = os.path.join(tmp, 'screens')
        subprocess.run([dart, 'run', 'tool/export_screens.dart', screens],
                       cwd=os.path.join(repo, 'Phone App', 'navigation'), check=True,
                       stdout=subprocess.DEVNULL)
        front_exe = os.path.join(tmp, 'front_test' + ext)
        build('front_test.cpp', front_exe)
        failed |= subprocess.run([front_exe, os.path.join(screens, 'packets.txt'),
                                  os.path.join(screens, 'dart.txt')]).returncode != 0
sys.exit(1 if failed else 0)
